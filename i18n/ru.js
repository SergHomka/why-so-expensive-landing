const pct = x => Math.round(x * 100) + '%';
function plural(n, one, few, many) {
  const a = n % 10, b = n % 100;
  const w = a === 1 && b !== 11 ? one : a >= 2 && a <= 4 && (b < 12 || b > 14) ? few : many;
  return n + ' ' + w;
}
function pages(tokens) {
  let p = Math.max(1, Math.round(tokens / E.TOKENS_PER_PAGE));
  if (p >= 20) p = Math.round(p / 10) * 10;       // «около 470 страниц», а не «около 472»
  return 'около ' + plural(p, 'страницы', 'страниц', 'страниц');
}
function times(x) {
  const r = x >= 10 ? Math.round(x) : Math.round(x * 10) / 10;
  if (r % 1) return String(r).replace('.', ',') + ' раза';        // «в 1,5 раза»
  return plural(r, 'раз', 'раза', 'раз');                              // «в 2 раза», «в 6 раз»
}
const nTimes = n => plural(n, 'раз', 'раза', 'раз');
