const day = ts => { const d = new Date(ts); return d.getDate() + ' ' + MONTHS[d.getMonth()]; };
// «с 9 по 23 сентября», «с 28 августа по 3 сентября», «за 23 сентября»
function period(a, b) {
  const x = new Date(a), y = new Date(b);
  if (day(a) === day(b)) return 'за ' + day(b);
  return 'с ' + (x.getMonth() === y.getMonth() ? x.getDate() : day(a)) + ' по ' + day(b);
}

